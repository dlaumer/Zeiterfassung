import assert from 'node:assert/strict';
import { loadHook } from './lib/load-hook.mjs';
const now = '2026-10-28T12:00:00';
class FixedDate extends Date { constructor(...args) { super(...(args.length ? args : [now])); } }
const review = loadHook('submission-review.js', { Date: FixedDate });
const record = (id, start, extra = {}) => ({ id, get: key => ({ participant: 'p', periodType: 'week', periodStart: start, submissionMode: 'initial', submittedAt: '2026-01-01', ...extra })[key] });
let weeks = 2;
const app = { findRecordsByFilter: () => [], findFirstRecordByFilter: () => ({ get: () => String(weeks) }) };
const starts = () => Array.from(review.editableWeeklyStarts(app, 'p'));
const edit = r => review.prepare(app, [r], { expectedSubmissionId: r.id, inputMode: 'totals' }, r.get('periodStart'), false);
assert.deepEqual(starts(), ['2026-10-26', '2026-10-19', '2026-10-12']);
edit(record('boundary', '2026-10-12'));
edit(record('current', '2026-10-26'));
assert.throws(() => edit(record('old', '2026-10-05')), /expired/);
weeks = 0;
assert.deepEqual(starts(), ['2026-10-26']);
assert.throws(() => edit(record('last', '2026-10-19')), /expired/);
edit(record('current', '2026-10-26'));
weeks = 2;
assert.throws(() => review.prepare(app, [record('day', '2026-10-11', { periodType: 'day' })], { expectedSubmissionId: 'day', inputMode: 'totals' }, '2026-10-11', false), /expired/);
console.log('PASS: configured calendar-week review boundaries, current week, zero-week setting and daily cutoff');
